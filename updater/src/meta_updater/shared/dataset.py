from pathlib import Path
from typing import Any

import yaml
from pydantic import TypeAdapter

from .files import update_bytes


class YamlDataset[T]:
    def __init__(
        self,
        path: Path,
        schema: Any,
        producer: str,
        note: str = "",
        *,
        exclude_none: bool = False,
        exclude_defaults: bool = False,
    ) -> None:
        self.path = path
        self.adapter = TypeAdapter(schema)
        self.producer = producer
        self.note = note
        self.exclude_none = exclude_none
        self.exclude_defaults = exclude_defaults

    def load(self, default: Any = None) -> T:
        if not self.path.exists():
            return self.adapter.validate_python(default)
        with self.path.open(encoding="utf-8") as file:
            return self.adapter.validate_python(yaml.safe_load(file))

    def update(self, value: Any, check: bool = False) -> bool:
        validated = self.adapter.validate_python(value)
        data = self.adapter.dump_python(
            validated,
            mode="python",
            exclude_none=self.exclude_none,
            exclude_defaults=self.exclude_defaults,
        )
        header = f"# Generated by {self.producer}. Do not edit by hand.\n"
        if self.note:
            header += f"# {self.note}\n"
        text = header + yaml.safe_dump(
            data, allow_unicode=True, sort_keys=False, width=1000
        )
        return update_bytes(self.path, text.encode(), check=check)
